// build-html.mjs — assemble src/index.html from src/html/ partials.
//
// The app ships with no bundler: src/index.html is copied verbatim to nginx
// (Dockerfile) and loaded straight from file:// by the Electron renderer under a
// strict `default-src 'self'` CSP — so runtime HTML includes (fetching fragments)
// are not an option. Instead we keep the markup in editable fragments under
// src/html/ and concatenate them at build time into the single file everything
// still expects. This runs as `prebuild`, so `npm run build` keeps index.html in
// sync; the generated src/index.html is committed (Electron loads it directly).
//
// Authoring: edit src/html/index.template.html and src/html/partials/*.html,
// then run `npm run build` (or `node scripts/build-html.mjs`). Never hand-edit
// src/index.html — it is overwritten.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = resolve(HERE, "..", "src");
const TEMPLATE = join(SRC, "html", "index.template.html");
const OUTPUT = join(SRC, "index.html");

// Matches an include on its own line, e.g. `      <!-- @include html/partials/topbar.html -->`.
const INCLUDE = /^\s*<!--\s*@include\s+(\S+)\s*-->\s*$/;

/** Read a fragment as an array of lines, dropping the single trailing newline. */
function readLines(path) {
  const text = readFileSync(path, "utf8");
  const lines = text.split("\n");
  if (lines.length > 0 && lines[lines.length - 1] === "") lines.pop();
  return lines;
}

/** Resolve a file's lines, expanding any @include directives it contains (recursively). */
function expand(path, stack = []) {
  if (stack.includes(path)) {
    throw new Error(
      `build-html: include cycle -> ${[...stack, path].join(" -> ")}`,
    );
  }
  const out = [];
  for (const line of readLines(path)) {
    const m = line.match(INCLUDE);
    if (m) {
      out.push(...expand(join(SRC, m[1]), [...stack, path]));
    } else {
      out.push(line);
    }
  }
  return out;
}

// Prepended to the generated file so anyone who opens index.html directly sees
// immediately that it is a build artifact and where the real source lives.
const BANNER = [
  "<!--",
  "  ⚠ AUTO-GENERATED — DO NOT EDIT THIS FILE.",
  "  Assembled from src/html/ by scripts/build-html.mjs (runs on `npm run build`).",
  "  To change the markup, edit src/html/index.template.html or src/html/partials/**",
  "  and rebuild. Any edit here is overwritten on the next build.",
  "-->",
];

function assemble() {
  const body = expand(TEMPLATE);
  writeFileSync(OUTPUT, [...BANNER, ...body].join("\n") + "\n");
  console.log(`build-html: wrote ${OUTPUT}`);
}

assemble();
